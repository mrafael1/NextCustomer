"""Writes the belt's perspective top face as pixel-art sources (mock-up B2, #80 step 6; its
scroll frames for #83; full build plan section 6.1). Python 3.11+ standard library only. Run
from the repo root:

    python tools/belt_art.py           # write art/src/scenery/belt_top.txt and its frames
    python tools/belt_art.py --check   # exit 1 when a committed source is not this output

then `python tools/pixel_art.py build` and `sh tools/import.sh`. The sources are generated: edit
this script, never the text files.

The belt runs left, toward the register, while the shift is counted (BeltPanel): FRAMES sources,
one per 2 px step of the slats along the front edge, wrap after one SLAT_PITCH. Frame 0 is
belt_top.txt, the still belt of planning; frame k (k >= 1) is
belt_top_scroll/belt_top_<2k>.txt, its slats 2k px further left. Only the slats move: every
other pixel is frame 0's.

The belt is seen with mock-up B2's one camera: a vanishing point far above the screen's centre
(VANISHING_POINT, stage pixels), so every edge that runs away from the player leans towards
it. The source covers ShiftStage.BELT_RECT from the guard's top down to the front edge of the
top face (the lip, apron and rail below it are the belt_front 3-slice), at 2 canvas px per art
px. Back to front:

- the steel guard along the far side: a lit top face, a rolled arris, the face and its shaded
  foot, with a dark moulded end cap at each end, an ink outline and its shadow on the hood;
- the hood's dark front face over the back roller, and its shadow on the rubber;
- the steel frame's top face, its lit left and shaded right inner walls, and the rubber in two
  bands (darker at the back) with a slat every SLAT_PITCH px, each a dark and a lit line.

The frame's and the guard's ends follow the receding outer edges; past them the art is
transparent, so the counter behind shows. Every receding x is snapped to the 2 px grid per art
row, so the edges step cleanly. Tests: python tools/belt_art_test.py
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCES = REPO / "art" / "src" / "scenery"
OUTPUT = SOURCES / "belt_top.txt"
# The scroll frames' folder under SOURCES (art/scenery/belt_top_scroll/ once built).
SCROLL_FOLDER = "belt_top_scroll"

# Stage pixels. The source's top-left is ShiftStage.BELT_RECT's (348, 314); it ends at the top
# face's front edge (FRONT_Y), where the lip starts.
ORIGIN = (348, 314)
FRONT_Y = 400
WIDTH_PX = 918
SCALE = 2
WIDTH = WIDTH_PX // SCALE
HEIGHT = (FRONT_Y - ORIGIN[1]) // SCALE
VANISHING_POINT = (640.0, -1600.0)
# The frame's outer edges and the rubber's edges at the front (the lip covers the frame's foot).
FRAME_LEFT, FRAME_RIGHT = 350, 1264
RUBBER_LEFT, RUBBER_RIGHT = 360, 1254
INNER_WALL = 6
# The guard: its top ink row, its face rows and the foot line; the end caps start one row
# higher and are CAP_WIDTH wide.
GUARD_TOP = 318
GUARD_FOOT = 330
CAP_TOP = 316
CAP_WIDTH = 8
# The hood's front face and its shadow, then the rubber's two bands.
HOOD_FRONT = (334, 338)
HOOD_SHADOW = (338, 340)
RUBBER_SPLIT = 366
SLAT_START = RUBBER_LEFT + 12
SLAT_PITCH = 20
# One frame per 2 px step of the slats: after FRAMES steps they are back on frame 0.
FRAMES = SLAT_PITCH // 2

TRANSPARENT = "."
INK = "#"
# art/src/palette.txt keys.
STEEL_HIGHLIGHT = "A"
STEEL_LIGHT = "B"
STEEL = "D"
STEEL_SHADE = "E"
STEEL_DARK = "H"
STEEL_DARKEST = "I"
RUBBER = "J"
RUBBER_DARK = "K"
CHARCOAL = "N"
KEYS = frozenset(
    {
        TRANSPARENT,
        INK,
        STEEL_HIGHLIGHT,
        STEEL_LIGHT,
        STEEL,
        STEEL_SHADE,
        STEEL_DARK,
        STEEL_DARKEST,
        RUBBER,
        RUBBER_DARK,
        CHARCOAL,
    }
)

HEADER = """; The belt's top face in perspective (mock-up B2, #80 step 6; mirrored, #83), {w}x{h} @2
; at ShiftStage.BELT_RECT's top (348,314) down to the lip (y 400). GENERATED by tools/belt_art.py:
; edit the script, never this file. Back to front: the steel guard with its end caps, the
; hood's front face, the steel frame with its lit left and shaded right inner walls, and the
; rubber in two bands with slats leaning to the vanishing point (640,-1600). Transparent past
; the frame's receding ends, so the counter shows.
{frame}@size {w}x{h}
@kind scenery
@scale 2
"""


def recede(x: float, y: float) -> float:
    """The x at height `y` of the receding edge that meets the front line (FRONT_Y) at `x`."""
    vx, vy = VANISHING_POINT
    return vx + (x - vx) * (y - vy) / (FRONT_Y - vy)


def snap(value: float) -> int:
    """`value` on the 2 px grid (halves round up)."""
    return int(math.floor(value / SCALE + 0.5)) * SCALE


def edges(front_left: int, front_right: int, row_y: int) -> tuple[int, int]:
    """The snapped receding edges, at the middle of the art row starting at `row_y`."""
    middle = row_y + SCALE / 2
    return snap(recede(front_left, middle)), snap(recede(front_right, middle))


def guard_key(row_y: int) -> str:
    """The guard's face, top to foot: lit top, arris, dark step, face, shaded foot band."""
    if row_y < GUARD_TOP + 2:
        return STEEL_LIGHT
    if row_y < GUARD_TOP + 4:
        return STEEL_HIGHLIGHT
    if row_y < GUARD_TOP + 6:
        return STEEL_DARK
    if row_y < GUARD_FOOT - 2:
        return STEEL
    return STEEL_SHADE


def cap_key(row_y: int) -> str:
    """An end cap's moulding: a lit top, then shade."""
    if row_y < CAP_TOP + 4:
        return STEEL
    if row_y < CAP_TOP + 6:
        return STEEL_SHADE
    return STEEL_DARKEST


class Grid:
    """The art grid, written in stage pixels (each art pixel covers SCALE x SCALE)."""

    def __init__(self) -> None:
        self.rows = [[TRANSPARENT] * WIDTH for _ in range(HEIGHT)]

    def span(self, row_y: int, start: int, end: int, key: str) -> None:
        """Fills stage x start..end (end excluded) on the art row starting at `row_y`."""
        row = (row_y - ORIGIN[1]) // SCALE
        if not 0 <= row < HEIGHT:
            return
        for x in range(start, end, SCALE):
            column = (x - ORIGIN[0]) // SCALE
            if 0 <= column < WIDTH:
                self.rows[row][column] = key

    def text(self) -> list[str]:
        return ["".join(row) for row in self.rows]


def _draw_frame(grid: Grid, row_y: int, shift: int) -> None:
    left, right = edges(FRAME_LEFT, FRAME_RIGHT, row_y)
    rubber_left, rubber_right = edges(RUBBER_LEFT, RUBBER_RIGHT, row_y)
    if row_y < HOOD_FRONT[1]:
        grid.span(row_y, left, right, STEEL_DARKEST)
    elif row_y < HOOD_SHADOW[1]:
        grid.span(row_y, left, right, STEEL_DARK)
        grid.span(row_y, rubber_left, rubber_right, CHARCOAL)
    else:
        grid.span(row_y, left, right, STEEL)
        grid.span(row_y, rubber_left, rubber_left + INNER_WALL, STEEL_LIGHT)
        grid.span(row_y, rubber_right - INNER_WALL, rubber_right, STEEL_DARK)
        inside = (rubber_left + INNER_WALL, rubber_right - INNER_WALL)
        band = RUBBER_DARK if row_y < RUBBER_SPLIT else RUBBER
        grid.span(row_y, inside[0], inside[1], band)
        for front_x in range(SLAT_START - shift, RUBBER_RIGHT, SLAT_PITCH):
            x = snap(recede(front_x, row_y + SCALE / 2))
            for offset, key in ((0, CHARCOAL), (SCALE, STEEL_DARKEST)):
                if inside[0] <= x + offset < inside[1]:
                    grid.span(row_y, x + offset, x + offset + SCALE, key)
    grid.span(row_y, left - SCALE, left, INK)
    grid.span(row_y, right, right + SCALE, INK)


def _draw_guard(grid: Grid) -> None:
    left, right = edges(FRAME_LEFT, FRAME_RIGHT, GUARD_TOP - SCALE)
    grid.span(GUARD_TOP - SCALE, left, right, INK)
    for row_y in range(GUARD_TOP, GUARD_FOOT, SCALE):
        left, right = edges(FRAME_LEFT, FRAME_RIGHT, row_y)
        grid.span(row_y, left, right, guard_key(row_y))
        grid.span(row_y, left - SCALE, left, INK)
        grid.span(row_y, right, right + SCALE, INK)
    left, right = edges(FRAME_LEFT, FRAME_RIGHT, GUARD_FOOT)
    grid.span(GUARD_FOOT, left - SCALE, right + SCALE, INK)
    left, right = edges(FRAME_LEFT, FRAME_RIGHT, GUARD_FOOT + SCALE)
    grid.span(GUARD_FOOT + SCALE, left, right, STEEL_DARKEST)
    grid.span(GUARD_FOOT + SCALE, left - SCALE, left, INK)
    grid.span(GUARD_FOOT + SCALE, right, right + SCALE, INK)


def _draw_caps(grid: Grid) -> None:
    for row_y in range(CAP_TOP - SCALE, GUARD_FOOT, SCALE):
        left, right = edges(FRAME_LEFT, FRAME_RIGHT, row_y)
        for start in (left, right - CAP_WIDTH):
            if row_y < CAP_TOP:
                grid.span(row_y, start, start + CAP_WIDTH, INK)
                continue
            grid.span(row_y, start, start + CAP_WIDTH, cap_key(row_y))
            grid.span(row_y, start - SCALE, start, INK)
            grid.span(row_y, start + CAP_WIDTH, start + CAP_WIDTH + SCALE, INK)


def shift_of(frame: int) -> int:
    """How far left (stage px, along the front edge) frame `frame`'s slats have moved."""
    return SCALE * (frame % FRAMES)


def generate(frame: int = 0) -> list[str]:
    """Frame `frame`'s pixel rows, top to bottom (frame 0: the still belt)."""
    grid = Grid()
    for row_y in range(HOOD_FRONT[0], FRONT_Y, SCALE):
        _draw_frame(grid, row_y, shift_of(frame))
    _draw_guard(grid)
    _draw_caps(grid)
    return grid.text()


def source_text(frame: int = 0) -> str:
    """Frame `frame`'s whole source file: the header, then the rows."""
    note = ""
    if frame != 0:
        note = f"; Scroll frame {frame}: its slats {shift_of(frame)} px left of frame 0's.\n"
    return HEADER.format(w=WIDTH, h=HEIGHT, frame=note) + "\n".join(generate(frame)) + "\n"


def frame_path(root: Path, frame: int) -> Path:
    """Where frame `frame`'s source goes under `root` (the scenery sources' folder)."""
    if frame == 0:
        return root / OUTPUT.name
    return root / SCROLL_FOLDER / f"belt_top_{shift_of(frame):02d}.txt"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="fail if a source is stale")
    parser.add_argument(
        "--root", type=Path, default=SOURCES, help="the scenery sources' folder to write in"
    )
    args = parser.parse_args(argv)
    stale = False
    for frame in range(FRAMES):
        path = frame_path(args.root, frame)
        text = source_text(frame)
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                print(f"{path}: stale, run python tools/belt_art.py", file=sys.stderr)
                stale = True
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
